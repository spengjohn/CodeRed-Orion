#!/usr/bin/env bash
# Build TensorFlow Lite + Edge TPU headers for CoralDriver (C++).
# RUN THIS ON THE RASPBERRY PI (not on macOS). Takes a while (often 45–120+ min).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
THIRD="$ROOT/third_party"
TF_DIR="$THIRD/tensorflow"
EDGETPU_DIR="$THIRD/libedgetpu"
BUILD_DIR="$THIRD/tflite_build"
ENV_FILE="$THIRD/coral/env.sh"
INCLUDE_DIR="$THIRD/coral/include"

# Must match google-coral/libedgetpu workspace.bzl (TF 2.16.1).
TF_COMMIT="${TF_COMMIT:-5bc9d26649cca274750ad3625bd93422617eed4b}"
TF_TAG_HINT="v2.16.1"
JOBS="${JOBS:-$(nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 2)}"

if [[ "$(uname -s)" != "Linux" ]]; then
  echo "This script must run on the Raspberry Pi (Linux), not $(uname -s)." >&2
  echo "Copy/sync this repo to the Pi, then:" >&2
  echo "  ./scripts/setup_coral_cpp.sh" >&2
  exit 1
fi

echo "==> Installing build packages"
sudo apt-get update
sudo apt-get install -y \
  build-essential \
  cmake \
  git \
  curl \
  ca-certificates \
  libusb-1.0-0-dev \
  zlib1g-dev

echo "==> Installing Edge TPU runtime matched to TF 2.16.1 (feranick)"
echo "    Google's coral-edgetpu apt package is often too old and segfaults with modern TFLite."
if [[ -x "$ROOT/scripts/fix_libedgetpu_tf216.sh" ]]; then
  "$ROOT/scripts/fix_libedgetpu_tf216.sh"
else
  echo "Missing scripts/fix_libedgetpu_tf216.sh" >&2
  exit 1
fi

echo "==> Locating libedgetpu shared library"
EDGETPU_SO="$(find /usr/lib /usr/local/lib -name 'libedgetpu.so*' 2>/dev/null | head -n 1 || true)"
if [[ -z "$EDGETPU_SO" ]]; then
  echo "libedgetpu.so* not found after package install." >&2
  echo "Check: dpkg -L libedgetpu1-std | grep '\\.so'" >&2
  exit 1
fi
echo "    found: $EDGETPU_SO"
# Help plain -ledgetpu if only the versioned .so.1 exists.
SO_DIR="$(dirname "$EDGETPU_SO")"
if [[ ! -e "$SO_DIR/libedgetpu.so" && -e "$SO_DIR/libedgetpu.so.1" ]]; then
  echo "==> Creating libedgetpu.so -> libedgetpu.so.1 symlink"
  sudo ln -sf libedgetpu.so.1 "$SO_DIR/libedgetpu.so"
  sudo ldconfig || true
fi

echo "==> Fetching edgetpu.h from libedgetpu"
mkdir -p "$INCLUDE_DIR" "$THIRD/coral"
if [[ ! -d "$EDGETPU_DIR/.git" ]]; then
  git clone --depth 1 https://github.com/google-coral/libedgetpu.git "$EDGETPU_DIR"
fi
cp -f "$EDGETPU_DIR/tflite/public/edgetpu.h" "$INCLUDE_DIR/edgetpu.h"

echo "==> Cloning TensorFlow @ $TF_COMMIT ($TF_TAG_HINT)"
mkdir -p "$THIRD"
if [[ ! -d "$TF_DIR/.git" ]]; then
  git clone https://github.com/tensorflow/tensorflow.git "$TF_DIR"
fi
git -C "$TF_DIR" fetch --depth 1 origin "$TF_COMMIT" || git -C "$TF_DIR" fetch origin "$TF_COMMIT"
git -C "$TF_DIR" checkout --force "$TF_COMMIT"

ARCH="$(uname -m)"
XNNPACK=ON
if [[ "$ARCH" == "armv7l" || "$ARCH" == "armv6l" ]]; then
  XNNPACK=OFF
fi

echo "==> Configuring TensorFlow Lite (CMake, XNNPACK=$XNNPACK)"
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"
cmake -S "$TF_DIR/tensorflow/lite" -B "$BUILD_DIR" \
  -DCMAKE_BUILD_TYPE=Release \
  -DTFLITE_ENABLE_XNNPACK="$XNNPACK"

echo "==> Building TensorFlow Lite (this is the long step; JOBS=$JOBS)"
cmake --build "$BUILD_DIR" -j"$JOBS"

LIB_CANDIDATE="$(find "$BUILD_DIR" -name 'libtensorflow-lite.a' | head -n 1 || true)"
if [[ -z "$LIB_CANDIDATE" ]]; then
  echo "Build finished but libtensorflow-lite.a was not found under $BUILD_DIR" >&2
  exit 1
fi

# Prefer linking through CMake (transitive deps). Still export paths for reference.
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup_coral_cpp.sh — source before ENABLE_CORAL builds.
export ENABLE_CORAL=1
export TFLITE_INCLUDE="$TF_DIR"
export TFLITE_LIB="$LIB_CANDIDATE"
export EDGETPU_INCLUDE="$INCLUDE_DIR"
export TENSORFLOW_SOURCE_DIR="$TF_DIR"
EOF

echo
echo "Done."
echo "  TensorFlow source : $TF_DIR"
echo "  libtensorflow-lite: $LIB_CANDIDATE"
echo "  edgetpu.h         : $INCLUDE_DIR/edgetpu.h"
echo "  env file          : $ENV_FILE"
echo
echo "Unplug/replug the Coral USB stick, then from the project root:"
echo "  source third_party/coral/env.sh"
echo "  ./compile_and_run"
echo
echo "Note: libtensorflow-lite.a is not fully self-contained. compile_and_run"
echo "uses a CMake path when ENABLE_CORAL=1 so transitive TFLite deps link correctly."
